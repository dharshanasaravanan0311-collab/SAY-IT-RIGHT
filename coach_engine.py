INDIAN_SCRIPTS = {
    "Hindi / Devanagari": r"[\u0900-\u097F]",
    "Bengali": r"[\u0980-\u09FF]",
    "Gurmukhi (Punjabi)": r"[\u0A00-\u0A7F]",
    "Gujarati": r"[\u0A80-\u0AFF]",
    "Odia": r"[\u0B00-\u0B7F]",
    "Tamil": r"[\u0B80-\u0BFF]",
    "Telugu": r"[\u0C00-\u0C7F]",
    "Kannada": r"[\u0C80-\u0CFF]",
    "Malayalam": r"[\u0D00-\u0D7F]",
    "Urdu / Perso-Arabic": r"[\u0600-\u06FF]",
}

HINGLISH_KEYWORDS = [
    r"\b(bhai|sir|madam|aap|tum|mera|meri|mere|mujhe|hum|kripya|please)\b",
    r"\b(kal|aaj|parso|urgent|jaldi|kaam|problem|dikkat|time|chahiye)\b",
    r"\b(ho gaya|nahi hua|kar do|kar dijiye|batao|de do|bhej do)\b",
    r"\b(dhanyawad|shukriya|namaste|pranam|vanakkam|namaskara)\b"
]

def detect_language(text: str) -> str:
    """Detects whether input is native Indian script, Hinglish, or English."""
    for lang, pattern in INDIAN_SCRIPTS.items():
        if re.search(pattern, text):
            return f"{lang} (Auto-Detected)"

    # Check for Hinglish
    hinglish_matches = sum(len(re.findall(pat, text, re.IGNORECASE)) for pat in HINGLISH_KEYWORDS)
    if hinglish_matches >= 2:
        return "Hinglish (Hindi + English Code-Switched)"

    return "English"

def extract_gemini_api_key(custom_key: Optional[str] = None) -> Optional[str]:
    """Retrieve Gemini API key from explicit param, .env, or environment."""
    if custom_key and custom_key.strip():
        return custom_key.strip()
    
    env_key = os.environ.get("GEMINI_API_KEY")
    if env_key and env_key.strip():
        return env_key.strip()
    
    env_path = os.path.join(os.path.dirname(__file__), ".env")
    if os.path.exists(env_path):
        try:
            with open(env_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line.startswith("GEMINI_API_KEY="):
                        val = line.split("=", 1)[1].strip().strip('"').strip("'")
                        if val:
                            return val
        except Exception:
            pass
    return None

def call_gemini_api(raw_draft: str, context: Dict[str, Any], api_key: str) -> Dict[str, Any]:
    """Calls Gemini REST API via urllib.request and parses structured JSON output."""
    chosen_format = context.get("target_format", "email").lower()
    chosen_tone = context.get("target_tone", "professional").lower()
    target_language = context.get("target_language", "English").strip()

    prompt = f"""
USER CONTEXT:
- Recipient Role: {context.get('recipient_role', 'Authority figure / Recipient')}
- Scenario: {context.get('scenario_title', 'High-Stakes Communication')}
- Desired Platform Format: {chosen_format} (email, whatsapp, or letter)
- Desired Tone Adjustment: {chosen_tone} (e.g. formal, casual, urgent, polite, persuasive)
- Source Input Language: {detect_language(raw_draft)}
- Target Output Language: {target_language}

USER'S RAW / TRANSCRIBED DRAFT:
\"\"\"{raw_draft}\"\"\"

TASK & LANGUAGE ROUTING RULES:
1. Ingest input. If Target Output Language is 'English' (default), translate any Hinglish or Indian regional language into clear, professional English.
2. If Target Output Language is explicitly requested as '{target_language}' (non-English, e.g. Hindi, Tamil, Gujarati, Spanish, French), generate the message completely in {target_language}.
3. Format specifically for {chosen_format.upper()} (Email with Subject, WhatsApp with mobile spacing/bullets/emojis, Formal Letter with traditional layout).
4. Align precisely to tone: {chosen_tone}.
5. Return strict JSON following the system schema.
"""
    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={api_key}"
    
    payload = {
        "contents": [
            {
                "role": "user",
                "parts": [{"text": prompt}]
            }
        ],
        "systemInstruction": {
            "parts": [{"text": SYSTEM_INSTRUCTION}]
        },
        "generationConfig": {
            "temperature": 0.3,
            "responseMimeType": "application/json"
        }
    }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )

    with urllib.request.urlopen(req, timeout=30) as resp:
        res_data = json.loads(resp.read().decode("utf-8"))
        candidate = res_data.get("candidates", [])[0]
        text_content = candidate.get("content", {}).get("parts", [])[0].get("text", "")
        text_content = re.sub(r"^```json\s*", "", text_content, flags=re.MULTILINE)
        text_content = re.sub(r"^```\s*$", "", text_content, flags=re.MULTILINE).strip()
        parsed = json.loads(text_content)
        parsed["source"] = "Gemini 2.5 Flash (Live AI)"
        return parsed

