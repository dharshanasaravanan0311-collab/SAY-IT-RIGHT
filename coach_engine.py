def smart_heuristic_coach(raw_draft: str, context: Dict[str, Any]) -> Dict[str, Any]:
    """
    Intelligent heuristic fallback engine.
    Supports Indian language detection, Platform Adapters (Email, WhatsApp, Letter),
    target output language generation, and iterative Tone Refinements.
    """
    detected_lang = detect_language(raw_draft)
    draft_lower = raw_draft.lower()
    scenario_id = context.get("scenario_id", "")
    target_format = context.get("target_format", "email").lower()
    target_tone = context.get("target_tone", "formal").lower()
    target_language = context.get("target_language", "English").strip()
    scenario = get_scenario_by_id(scenario_id) if scenario_id else None

    # Detect anti-patterns
    anti_patterns = []
    apology_count = len(re.findall(r"\b(sorry|apologize|apologies|forgive|maaf)\b", draft_lower))
    if apology_count >= 2:
        anti_patterns.append({
            "name": "Over-Apologizing Syndrome",
            "snippet": "Repeated apologies",
            "why_it_hurts": f"Apologizing {apology_count} times dilutes authority and creates recipient hesitation."
        })
    elif "hate to bother" in draft_lower or "sorry to bother" in draft_lower or "disturb" in draft_lower:
        anti_patterns.append({
            "name": "Excessive Throat-Clearing",
            "snippet": "sorry to bother / disturb you",
            "why_it_hurts": "Signals unnecessary guilt. Asking for legitimate accommodations is standard professional protocol."
        })

    if any(q in draft_lower for q in ["maybe", "is there anyway", "kuch time", "some extra time"]):
        anti_patterns.append({
            "name": "Vague / Hesitant Ask",
            "snippet": "maybe get some extra time",
            "why_it_hurts": "Leaves the timeline open-ended and shifts calculation work onto the recipient."
        })

    if "not my fault" in draft_lower or "galti" in draft_lower or "harshly" in draft_lower:
        anti_patterns.append({
            "name": "Defensive Posturing",
            "snippet": "Focusing on blame",
            "why_it_hurts": "Triggers defensive responses from reviewers. Focus on objective facts."
        })

    if not anti_patterns:
        anti_patterns.append({
            "name": "Under-Specified Call-to-Action",
            "snippet": "Unclear next steps",
            "why_it_hurts": "The recipient may not immediately know what resolution you need."
        })

    # Tone scoring
    clarity_score = 3
    if any(w in draft_lower for w in ["assignment", "friday", "deadline", "error", "rubric", "tarikh"]):
        clarity_score += 1
    if apology_count >= 2:
        clarity_score -= 1
    clarity_score = max(1, min(5, clarity_score))

    assertiveness_score = 4 - len(anti_patterns)
    assertiveness_score = max(1, min(5, assertiveness_score))
    deference_score = 4 if apology_count >= 1 else 3
    warmth_score = 4 if target_tone in ["polite", "casual"] else 3

    readiness = max(35, 90 - (len(anti_patterns) * 16) - (apology_count * 8))

    recipient_role = context.get("recipient_role") or (scenario["recipient_role"] if scenario else "Recipient")
    recipient_lens = {
        "who_they_are": recipient_role,
        "what_they_care_about": scenario["recipient_mindset"] if scenario else "Brevity, directness, and actionable timelines without emotional drama.",
        "first_impression_of_raw_draft": "Appears anxious and hesitant; core request is buried."
    }

    # Generate Localized Messages for the requested target language
    scenario_title = context.get("scenario_title", "Important Update")
    localized = get_localized_messages(target_language, recipient_role, scenario_title, target_tone)

    email_subject = localized["email_subject"]
    email_body = localized["email_body"]
    whatsapp_body = localized["whatsapp_body"]
    letter_body = localized["letter_body"]

    rewrites = [
        {
            "format": "email",
            "style": f"Email Format 📨 ({target_language})",
            "tagline": f"Best for email correspondence generated in {target_language}",
            "subject_line": email_subject,
            "message": email_body,
            "calibrated_metrics": {
                "assertiveness": 4,
                "warmth": 3,
                "deference": 4,
                "clarity": 5
            },
            "pedagogical_diffs": [
                {
                    "original": "sorry to bother you / please extra time",
                    "replacement": f"Translated into polite, structured {target_language}",
                    "rule_of_thumb": "State request in sentence #1 with a concrete timestamp.",
                    "psychology": "Directness respects recipient time and eliminates ambiguous back-and-forth."
                }
            ]
        },
        {
            "format": "whatsapp",
            "style": f"WhatsApp Message 💬 ({target_language})",
            "tagline": f"Structured for fast mobile reading with clean bullet points in {target_language}",
            "subject_line": None,
            "message": whatsapp_body,
            "calibrated_metrics": {
                "assertiveness": 4,
                "warmth": 4,
                "deference": 3,
                "clarity": 5
            },
            "pedagogical_diffs": [
                {
                    "original": "Long unstructured paragraph",
                    "replacement": f"Bullet-point breakdown in {target_language}",
                    "rule_of_thumb": "Use spacing and bullet points for mobile communication.",
                    "psychology": "Mobile readers skim messages in 5 seconds; bullets ensure key details are never missed."
                }
            ]
        },
        {
            "format": "letter",
            "style": f"Formal Physical Letter 📝 ({target_language})",
            "tagline": f"Formatted for physical print or official PDF documentation in {target_language}",
            "subject_line": email_subject,
            "message": letter_body,
            "calibrated_metrics": {
                "assertiveness": 3,
                "warmth": 2,
                "deference": 5,
                "clarity": 5
            },
            "pedagogical_diffs": [
                {
                    "original": "Casual phrasing",
                    "replacement": f"Rigid block-paragraph structure in {target_language}",
                    "rule_of_thumb": "Adhere to formal physical address protocols.",
                    "psychology": "Institutional gatekeepers expect institutional formality for official records."
                }
            ]
        }
    ]

    return {
        "source": "Say It Right Pedagogical Rule Engine (Zero-Latency)",
        "detected_language": detected_lang,
        "target_language": target_language,
        "selected_format": target_format,
        "active_tone": target_tone.capitalize(),
        "diagnostic": {
            "readiness_score": readiness,
            "primary_barrier": anti_patterns[0]["name"] if anti_patterns else "Clarity Calibration Needed",
            "anti_patterns": anti_patterns,
            "recipient_lens": recipient_lens,
            "tone_metrics": {
                "assertiveness": assertiveness_score,
                "warmth": warmth_score,
                "deference": deference_score,
                "clarity": clarity_score
            }
        },
        "calibrated_rewrites": rewrites,
        "feedback_hook": "Does this output satisfy your need, or would you like to change the tone? 🔍 (e.g., make it more formal, casual, urgent, polite, persuasive, etc.)",
        "follow_up_playbook": {
            "recommended_wait_window": "36-48 business hours",
            "if_no_response": localized["nudge"],
            "if_rejected": localized["rejected"]
        }
    }

def analyze_communication(raw_draft: str, context: Dict[str, Any], custom_api_key: Optional[str] = None) -> Dict[str, Any]:
    """Main routing function for communication coaching."""
    api_key = extract_gemini_api_key(custom_api_key)
    
    if api_key:
        try:
            return call_gemini_api(raw_draft, context, api_key)
        except Exception as e:
            fallback = smart_heuristic_coach(raw_draft, context)
            fallback["warning"] = f"Live Gemini request fallback: {str(e)[:100]}"
            return fallback
    else:
        return smart_heuristic_coach(raw_draft, context)
