  const targetTone = (context.target_tone || 'formal').toLowerCase();
  const targetLanguage = (context.target_language || 'English').trim();
  const scenario = scenarioId ? getScenarioById(scenarioId) : null;

  // Detect anti-patterns
  const antiPatterns = [];
  const apologyMatches = draftLower.match(/\b(sorry|apologize|apologies|forgive|maaf)\b/g);
  const apologyCount = apologyMatches ? apologyMatches.length : 0;

  if (apologyCount >= 2) {
    antiPatterns.push({
      name: "Over-Apologizing Syndrome",
      snippet: "Repeated apologies",
      why_it_hurts: `Apologizing ${apologyCount} times dilutes authority and creates recipient hesitation.`
    });
  } else if (draftLower.includes("hate to bother") || draftLower.includes("sorry to bother") || draftLower.includes("disturb")) {
    antiPatterns.push({
      name: "Excessive Throat-Clearing",
      snippet: "sorry to bother / disturb you",
      why_it_hurts: "Signals unnecessary guilt. Asking for legitimate accommodations is standard professional protocol."
    });
  }

  if (draftLower.includes("maybe") || draftLower.includes("is there anyway") || draftLower.includes("kuch time") || draftLower.includes("some extra time")) {
    antiPatterns.push({
      name: "Vague / Hesitant Ask",
      snippet: "maybe get some extra time",
      why_it_hurts: "Leaves the timeline open-ended and shifts calculation work onto the recipient."
    });
  }

  if (draftLower.includes("not my fault") || draftLower.includes("galti") || draftLower.includes("harshly")) {
    antiPatterns.push({
      name: "Defensive Posturing",
      snippet: "Focusing on blame",
      why_it_hurts: "Triggers defensive responses from reviewers. Focus on objective facts."
    });
  }

  if (antiPatterns.length === 0) {
    antiPatterns.push({
      name: "Under-Specified Call-to-Action",
      snippet: "Unclear next steps",
      why_it_hurts: "The recipient may not immediately know what resolution you need."
    });
  }

  // Tone scoring
  let clarityScore = 3;
  if (/assignment|friday|deadline|error|rubric|tarikh/i.test(draftLower)) {
    clarityScore += 1;
  }
  if (apologyCount >= 2) {
    clarityScore -= 1;
  }
  clarityScore = Math.max(1, Math.min(5, clarityScore));

  let assertivenessScore = Math.max(1, Math.min(5, 4 - antiPatterns.length));
  const deferenceScore = apologyCount >= 1 ? 4 : 3;
  const warmthScore = ['polite', 'casual'].includes(targetTone) ? 4 : 3;

  const readiness = Math.max(35, 90 - (antiPatterns.length * 16) - (apologyCount * 8));

  const recipientRole = context.recipient_role || (scenario ? scenario.recipient_role : "Recipient");
