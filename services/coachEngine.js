const INDIAN_SCRIPTS = {
  "Hindi / Devanagari": /[\u0900-\u097F]/,
  "Bengali": /[\u0980-\u09FF]/,
  "Gurmukhi (Punjabi)": /[\u0A00-\u0A7F]/,
  "Gujarati": /[\u0A80-\u0AFF]/,
  "Odia": /[\u0B00-\u0B7F]/,
  "Tamil": /[\u0B80-\u0BFF]/,
  "Telugu": /[\u0C00-\u0C7F]/,
  "Kannada": /[\u0C80-\u0CFF]/,
  "Malayalam": /[\u0D00-\u0D7F]/,
  "Urdu / Perso-Arabic": /[\u0600-\u06FF]/,
};

const HINGLISH_KEYWORDS = [
  /\b(bhai|sir|madam|aap|tum|mera|meri|mere|mujhe|hum|kripya|please)\b/i,
  /\b(kal|aaj|parso|urgent|jaldi|kaam|problem|dikkat|time|chahiye)\b/i,
  /\b(ho gaya|nahi hua|kar do|kar dijiye|batao|de do|bhej do)\b/i,
  /\b(dhanyawad|shukriya|namaste|pranam|vanakkam|namaskara)\b/i
];

export function detectLanguage(text) {
  for (const [lang, pattern] of Object.entries(INDIAN_SCRIPTS)) {
    if (pattern.test(text)) {
      return `${lang} (Auto-Detected)`;
    }
  }

  let hinglishMatches = 0;
  for (const pat of HINGLISH_KEYWORDS) {
    const matches = text.match(new RegExp(pat.source, 'gi'));
    if (matches) hinglishMatches += matches.length;
  }

  if (hinglishMatches >= 2) {
    return "Hinglish (Hindi + English Code-Switched)";
  }

  return "English";
}

export function extractGeminiApiKey(customKey = null) {
  if (customKey && typeof customKey === 'string' && customKey.trim()) {
    return customKey.trim();
  }
  if (process.env.GEMINI_API_KEY && process.env.GEMINI_API_KEY.trim()) {
    return process.env.GEMINI_API_KEY.trim();
  }
  return null;
}

